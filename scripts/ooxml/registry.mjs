import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { isAbsolute, relative, resolve } from "node:path";

export const dimensions = Object.freeze(["import","render","edit","export","preserve"]);
const profiles = new Set(["transitional","strict","extension","opc"]);
const compare = (a,b) => a < b ? -1 : a > b ? 1 : 0;
export const keyOf = e => JSON.stringify([e.profile,e.namespace,e.element,e.context]);
export const stringify = value => JSON.stringify(value,null,2) + "\n";
export const digest = value => createHash("sha256").update(value).digest("hex");

export function validateSeed(seed, root) {
  if (seed.version !== 1 || !Array.isArray(seed.entries) || seed.inventory?.status !== "incomplete") throw Error("Invalid seed version or inventory status");
  const keys = new Set();
  for (const e of seed.entries) {
    if (!profiles.has(e.profile) || ![e.namespace,e.element,e.context,e.domain].every(v=>typeof v==="string" && v.trim())) throw Error("Invalid capability identity");
    if (keys.has(keyOf(e))) throw Error("Duplicate capability: "+keyOf(e));
    keys.add(keyOf(e));
    if (!Array.isArray(e.limitations) || !e.limitations.length || e.limitations.some(v=>typeof v!=="string" || !v.trim())) throw Error("Missing limitations");
    if (!Array.isArray(e.missing) || !e.missing.every(d=>dimensions.includes(d)) || !Array.isArray(e.evidence)) throw Error("Invalid dimensions/evidence");
    for (const ev of e.evidence) {
      if (typeof ev.file!=="string" || isAbsolute(ev.file) || !ev.file.startsWith("tests/vitest/") || !ev.file.endsWith(".test.ts") || ev.file.split("/").includes("..")) throw Error("Invalid evidence path");
      if (typeof ev.case!=="string" || !ev.case.trim() || !Array.isArray(ev.dimensions) || !ev.dimensions.length || ev.dimensions.some(d=>!dimensions.includes(d)||e.missing.includes(d))) throw Error("Invalid evidence case or dimensions");
      if(root) {
        const file = resolve(root,ev.file);
        if(relative(root,file).startsWith("..")) throw Error("Evidence outside repo");
        const text=readFileSync(file,"utf8");
        // Verify the leaf title is declared in the file; the runner checks fullName.
        if(!text.includes(JSON.stringify(ev.case).slice(1,-1)) && !ev.case.split(" ").some((_,i,a)=>i>0 && text.includes(JSON.stringify(a.slice(i).join(" "))))) throw Error("Evidence title not found: "+ev.case);
      }
    }
  }
  return seed;
}

export function observedCases(result, root) {
  const cases = new Map();
  for(const suite of result?.testResults ?? []) {
    if(typeof suite.name!=="string") continue;
    const file=relative(root,resolve(root,suite.name)).split("\\").join("/");
    for(const assertion of suite.assertionResults ?? []) {
      if(typeof assertion.fullName!=="string") continue;
      const key=JSON.stringify([file,assertion.fullName]);
      const statuses=cases.get(key)??[];
      statuses.push(assertion.status);
      cases.set(key,statuses);
    }
  }
  return cases;
}

export function buildReport(seed,{root=process.cwd(),testResult=null,sourceRef=null,inventory=null}={}) {
  validateSeed(seed,root);
  const cases=observedCases(testResult,root);
  const entries=[...seed.entries].sort((a,b)=>compare(keyOf(a),keyOf(b))).map(e=>{
    const support=Object.fromEntries(dimensions.map(d=>[d,e.missing.includes(d)?"missing":"unknown"]));
    const evidence=e.evidence.map(ev=>{
      const statuses=cases.get(JSON.stringify([ev.file,ev.case]))??[];
      const observed=statuses.length===0?"notRun":statuses.every(s=>s==="passed")?"passed":statuses.some(s=>s==="failed")?"failed":"notPassed";
      return {...ev,observed};
    });
    // This initial seed is deliberately scoped to individual cases. Passing a
    // narrow test proves partial behavior only, never whole-element support.
    for(const d of dimensions) {
      const relevant=evidence.filter(ev=>ev.dimensions.includes(d));
      if(relevant.length && relevant.every(ev=>ev.observed==="passed")) support[d]="partial";
    }
    return {...e,evidence,support};
  });
  return {version:1,sourceRef,auditRef:seed.auditRef,auditDate:seed.auditDate,
    inventory:inventory??seed.inventory, evidenceMode:testResult?"runner-results":"static-audit-only",
    denominator:null, dimensions, entries};
}
export function assertEvidence(report) {
  const absent=report.entries.flatMap(e=>e.evidence.filter(ev=>ev.observed!=="passed").map(ev=>ev.file+" :: "+ev.case+" ("+ev.observed+")"));
  if(absent.length) throw Error("Missing or failing OOXML evidence:\n"+absent.join("\n"));
}
export function markdown(report) {
  const safe=s=>String(s).replaceAll("|","\\|").replaceAll("\n"," ");
  return ["# OOXML capability report","","Generated by npm run ooxml:report.",
    "", "Source: "+(report.sourceRef??"unrecorded"),"Evidence: "+report.evidenceMode,
    "Inventory: "+report.inventory.status+". "+(report.inventory.reason??""),
    "No global percentage: the denominator is unverified.","",
    "| Profile | Element | Context | Import | Render | Edit | Export | Preserve | Limitations |",
    "|---|---|---|---|---|---|---|---|---|",
    ...report.entries.map(e=>"| "+[e.profile,e.element,e.context,...dimensions.map(d=>e.support[d]),e.limitations.join(" ")].map(safe).join(" | ")+" |"),""].join("\n");
}
